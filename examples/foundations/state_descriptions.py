"""Section 1.3: state descriptions, readout settings and constructed records.

Reuses Section 1.2's independent real-matrix reference. No random shots or hardware.
Run from the repository root with the pinned requirements-examples.txt environment.
"""
from fractions import Fraction
from importlib.metadata import version
from itertools import product

import flagquantum as fq
import torch

from interference import H, OPTIONS, S, apply, reference


def evaluate(preparation, recombine):
    gates = preparation + (["h"] if recombine else [])
    pair = reference(gates)
    circuit = fq.Circuit(1, dtype=torch.complex128)
    for gate in gates:
        if gate == "h":
            circuit.h(0)
        else:
            circuit.z(0)
    result = fq.run(circuit, outputs=[fq.probabilities()], options=OPTIONS)
    torch.testing.assert_close(result.statevector()[0],
                               torch.tensor(pair, dtype=torch.complex128), rtol=0, atol=1e-12)
    expected = torch.tensor([a*a for a in pair], dtype=torch.float64)
    torch.testing.assert_close(result.probabilities[0], expected, rtol=0, atol=1e-12)
    return pair, result.probabilities[0]


def record_probability(record, probabilities):
    # Probability of an ordered sequence under the assumed independent-shot model.
    weight = Fraction(1)
    for bit in record:
        weight *= probabilities[bit]
    return weight


def main():
    assert version("flagquantum") == "0.3.1", "Revalidate before changing the pinned release."
    direct_probabilities = []
    for label, preparation, expected_pair, recombined_p0 in [
        ("A", ["h"], [S, S], 1.0),
        ("B", ["h", "z"], [S, -S], 0.0),
    ]:
        pair, direct = evaluate(preparation, False)
        torch.testing.assert_close(torch.tensor(pair, dtype=torch.float64), torch.tensor(expected_pair, dtype=torch.float64), rtol=0, atol=1e-12)
        torch.testing.assert_close(direct, torch.tensor([0.5, 0.5], dtype=torch.float64), rtol=0, atol=1e-12)
        _, recombined = evaluate(preparation, True)
        torch.testing.assert_close(recombined, torch.tensor([recombined_p0, 1-recombined_p0],
                                                          dtype=torch.float64), rtol=0, atol=1e-12)
        direct_probabilities.append(direct)
        print(f"Preparation {label}: direct P(0)={direct[0].item():.9f}; after H P(0)={recombined[0].item():.9f}")
    torch.testing.assert_close(direct_probabilities[0], direct_probabilities[1], rtol=0, atol=1e-12)

    # Constructed data, not generated by the simulator and not measured on a device.
    record = [0, 1, 0, 1, 1, 0, 0, 1]
    model_a = model_b = (Fraction(1, 2), Fraction(1, 2))
    likelihood_a = record_probability(record, model_a)
    likelihood_b = record_probability(record, model_b)
    assert likelihood_a == likelihood_b == Fraction(1, 256)
    # Include unbalanced records too: equal model probabilities do not require equal counts.
    for short_record in product((0, 1), repeat=4):
        assert record_probability(short_record, model_a) == record_probability(short_record, model_b)
    assert record_probability([1]*8, model_a) == Fraction(1, 256)
    # Reversing both signs preserves predictions in the two settings checked here.
    for recombine in (False, True):
        positive = apply(H, [S, S]) if recombine else [S, S]
        negative = apply(H, [-S, -S]) if recombine else [-S, -S]
        torch.testing.assert_close(torch.tensor([a*a for a in positive], dtype=torch.float64),
                                   torch.tensor([a*a for a in negative], dtype=torch.float64), rtol=0, atol=1e-12)
    print(f"Constructed record: {''.join(map(str, record))}; zeros={record.count(0)}, ones={record.count(1)}")
    print(f"Probability of this ordered record: A={likelihood_a}, B={likelihood_b}")
    print(f"Fixture's second readout: {record[1]} (not an amplitude pair)")
    print("State, setting, and record checks passed (atol=1e-12).")


if __name__ == "__main__":
    main()
